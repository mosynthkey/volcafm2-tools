// DX7 FM routing flags. Values follow the Apache-2.0 FmCore algorithm table
// used by Dexed; graph layout/rendering is implemented independently here.
export const DX7_ALGORITHM_FLAGS: readonly (readonly number[])[] = [
  [0xc1,0x11,0x11,0x14,0x01,0x14],[0x01,0x11,0x11,0x14,0xc1,0x14],
  [0xc1,0x11,0x14,0x01,0x11,0x14],[0xc1,0x11,0x94,0x01,0x11,0x14],
  [0xc1,0x14,0x01,0x14,0x01,0x14],[0xc1,0x94,0x01,0x14,0x01,0x14],
  [0xc1,0x11,0x05,0x14,0x01,0x14],[0x01,0x11,0xc5,0x14,0x01,0x14],
  [0x01,0x11,0x05,0x14,0xc1,0x14],[0x01,0x05,0x14,0xc1,0x11,0x14],
  [0xc1,0x05,0x14,0x01,0x11,0x14],[0x01,0x05,0x05,0x14,0xc1,0x14],
  [0xc1,0x05,0x05,0x14,0x01,0x14],[0xc1,0x05,0x11,0x14,0x01,0x14],
  [0x01,0x05,0x11,0x14,0xc1,0x14],[0xc1,0x11,0x02,0x25,0x05,0x14],
  [0x01,0x11,0x02,0x25,0xc5,0x14],[0x01,0x11,0x11,0xc5,0x05,0x14],
  [0xc1,0x14,0x14,0x01,0x11,0x14],[0x01,0x05,0x14,0xc1,0x14,0x14],
  [0x01,0x14,0x14,0xc1,0x14,0x14],[0xc1,0x14,0x14,0x14,0x01,0x14],
  [0xc1,0x14,0x14,0x01,0x14,0x04],[0xc1,0x14,0x14,0x14,0x04,0x04],
  [0xc1,0x14,0x14,0x04,0x04,0x04],[0xc1,0x05,0x14,0x01,0x14,0x04],
  [0x01,0x05,0x14,0xc1,0x14,0x04],[0x04,0xc1,0x11,0x14,0x01,0x14],
  [0xc1,0x14,0x01,0x14,0x04,0x04],[0x04,0xc1,0x11,0x14,0x04,0x04],
  [0xc1,0x14,0x04,0x04,0x04,0x04],[0xc4,0x04,0x04,0x04,0x04,0x04],
];

export interface AlgorithmGraphNode { id: number; x: number; y: number; carrier: boolean; feedback: boolean; }
export interface AlgorithmGraphEdge { from: number; to: number; }

export const buildAlgorithmGraph = (algorithm: number): { nodes: AlgorithmGraphNode[]; edges: AlgorithmGraphEdge[] } => {
  const flags = DX7_ALGORITHM_FLAGS[algorithm] ?? DX7_ALGORITHM_FLAGS[0];
  const busProducers: number[][] = [[], [], []];
  const edges: AlgorithmGraphEdge[] = [];
  const carriers = new Set<number>();
  const feedback = new Set<number>();

  flags.forEach((flag, index) => {
    const id = 6 - index;
    const inputBus = (flag >> 4) & 0x03;
    const outputBus = flag & 0x03;
    if (inputBus > 0) busProducers[inputBus].forEach(from => edges.push({ from, to: id }));
    if (outputBus === 0) carriers.add(id);
    else if ((flag & 0x04) !== 0) busProducers[outputBus].push(id);
    else busProducers[outputBus] = [id];
    if ((flag & 0xc0) !== 0) feedback.add(id);
  });

  const depths = new Map<number, number>();
  const depthOf = (id: number, visiting = new Set<number>()): number => {
    if (depths.has(id)) return depths.get(id)!;
    if (visiting.has(id)) return 0;
    visiting.add(id);
    const targets = edges.filter(edge => edge.from === id).map(edge => edge.to);
    const depth = targets.length ? 1 + Math.max(...targets.map(target => depthOf(target, visiting))) : 0;
    depths.set(id, depth);
    return depth;
  };
  for (let id = 1; id <= 6; id++) depthOf(id);
  const rows = new Map<number, number[]>();
  for (let id = 1; id <= 6; id++) {
    const depth = depths.get(id) ?? 0;
    rows.set(depth, [...(rows.get(depth) ?? []), id]);
  }
  const nodes: AlgorithmGraphNode[] = [];
  rows.forEach((ids, depth) => ids.forEach((id, index) => nodes.push({
    id,
    x: 12 + ((index + 1) / (ids.length + 1)) * 216,
    // 48px leaves at least 14px of visible stem on both sides of a routed arrow.
    y: 280 - depth * 48,
    carrier: carriers.has(id),
    feedback: feedback.has(id),
  })));
  return { nodes, edges };
};
